def fmt_cols(cols):
    return ', '.join(f'`{c}`' for c in cols) if cols else '*(columns not resolved — see file)*'


def fmt_writes(w):
    if isinstance(w, dict) and ('ops' in w or 'columns' in w):
        ops = '/'.join(w.get('ops', []))
        cols = w.get('columns') or []
        return f"{ops}" + (f" — {fmt_cols(cols)}" if cols else '')
    if isinstance(w, dict):  # notes form {insert:[..], update:[..], delete:"cond"}
        parts = []
        for k, v in w.items():
            parts.append(f"{k}: {fmt_cols(v) if isinstance(v, list) else v}")
        return '; '.join(parts)
    return str(w)


def render_entry(m, p):
    e, a, n = m.files[p], m.files[p]['auto'], m.notes(p)
    L = [f'### {p}', '', f'{link(p)} · **{e["kind"]}** · {m.reviewed(p)}', '']
    if m.purpose(p):
        L += [m.purpose(p), '']
    if a.get('defines'):
        L.append('**Defines:** ' + ', '.join(f"{d['type']} `{d['name']}`" for d in a['defines']))
    params = a.get('params') or {}
    pnotes = n.get('params', {}) if isinstance(n.get('params'), dict) else {}
    for obj, ps in params.items():
        if ps:
            L.append(f'**Parameters ({obj}):** ' + ', '.join(
                f"`@{x['name']} {x['type']}`" + (f" — {pnotes[x['name']]}" if x['name'] in pnotes else '') for x in ps))
    if a.get('declares'):
        L.append('**Template variables:** ' + ', '.join(
            f"`@{d['name']} {d['type']}`" + (f" = `{d['default']}`" if d.get('default') else '') for d in a['declares']))
    if n.get('access'):
        L.append(f"**Access / row scope:** {n['access']}")
    elif a.get('accessSignals'):
        s = a['accessSignals']
        bits = []
        if s.get('callerParams'):
            bits.append('caller-scoped via ' + '/'.join(s['callerParams']))
        if s.get('rolesReferenced'):
            bits.append('roles: ' + ', '.join(s['rolesReferenced']))
        for k, lab in (('usesStaffSchoolAccess', 'StaffSchoolAccess'), ('usesFactSectionTeachers', 'FactSectionTeachers'),
                       ('usesStaffAppAccess', 'StaffAppAccess')):
            if s.get(k):
                bits.append(lab)
        L.append('**Access signals (auto):** ' + '; '.join(bits))
    if a.get('grants'):
        L.append('**Grants:** ' + ', '.join(f"{g['perm']} on `{g['object']}` → {g['to']}" for g in a['grants']))
    if a.get('gates') and e['kind'] in ('page', 'action', 'api-route', 'component', 'app-component'):
        labels = sorted(set(g['gate'] for g in a['gates']))
        L.append('**App gates (auto):** ' + ', '.join(labels))
    reads = m.reads(p)
    if reads:
        L.append('**Reads:**')
        for t, cols in sorted(reads.items()):
            L.append(f'- `{t}` — {fmt_cols(cols)}')
    writes = m.writes(p)
    if writes:
        L.append('**Writes:**')
        for t, w in sorted(writes.items()):
            L.append(f'- `{t}` — {fmt_writes(w)}')
    if a.get('callsFunctions'):
        L.append('**Calls functions:** ' + ', '.join(f'`{x}`' for x in a['callsFunctions']))
    if a.get('execs'):
        L.append('**Executes:** ' + ', '.join(f'`{x}`' for x in a['execs']))
    if a.get('dataFunctions'):
        L.append('**data.ts calls:** ' + ', '.join(f'`{x}`' for x in a['dataFunctions']))
    if a.get('execProcs'):
        L.append('**Procedures called:** ' + ', '.join(f'`{x}`' for x in a['execProcs']))
    errs = n.get('errors') or []
    if errs:
        L.append('**Errors raised:**')
        for x in errs:
            L.append(f"- {x.get('code') or ''} {('“' + x['message'] + '”') if x.get('message') else ''} — {x.get('condition', '')}")
    elif a.get('errors'):
        L.append('**Errors raised (auto):**')
        for x in a['errors']:
            L.append(f"- {x.get('code') or x.get('kind', '')} “{x['message']}” (line {x['line']})")
    used = n.get('usedIn')
    if used:
        L.append('**Used in the app:**')
        for u in used:
            L.append(f"- `{u.get('route')}` — {u.get('trigger', '')}")
    else:
        ui = m.used_in(p)
        if ui:
            L.append('**Used on routes (auto):** ' + ', '.join(f'`{r}`' for r in ui))
    if n.get('caveats'):
        L.append(f"**Caveats:** {n['caveats']}")
    L.append('')
    return '\n'.join(L)


KIND_ORDER = ['table', 'staging-table', 'security-table', 'procedure', 'function', 'legacy-view', 'grants', 'sql',
              'page', 'action', 'api-route', 'data-module', 'lib', 'component', 'app-component', 'script']
KIND_TITLE = {'table': 'Tables (dimensions & facts)', 'staging-table': 'Staging tables',
              'security-table': 'Security tables', 'procedure': 'Stored procedures (usp_*)',
              'function': 'Table-valued functions (tvf_*)', 'legacy-view': 'Legacy views (vw_*, Power Apps era)',
              'grants': 'Grants', 'sql': 'Other SQL', 'page': 'App pages', 'action': 'Server actions', 'api-route': 'API routes',
              'data-module': 'Data module (lib/data.ts)', 'lib': 'Library', 'component': 'Components',
              'app-component': 'Route-local components', 'script': 'SQL scripts (diagnostics, fixes, seeds)'}


def build_by_file(m):
    by_kind = defaultdict(list)
    for p, e in m.files.items():
        if e['kind'] != 'script':      # scripts have their own document
            by_kind[e['kind']].append(p)
    L = [HEADER + '# Catalog — by file', '',
         f"Extracted {m.cat.get('extractedAt')} from `{m.cat.get('extractedFrom')}`. "
         'Scripts are in [scripts.md](scripts.md). “(auto)” = mechanically extracted, not yet verified by reading.', '']
    for k in KIND_ORDER:
        if by_kind.get(k):
            L.append(f'- [{KIND_TITLE[k]}](#{anchor(KIND_TITLE[k])}) ({len(by_kind[k])})')
    L.append('')
    for k in KIND_ORDER:
        if not by_kind.get(k):
            continue
        L += [f'## {KIND_TITLE[k]}', '']
        for p in sorted(by_kind[k]):
            L.append(render_entry(m, p))
    if 'webapp/src/lib/data.ts' in m.files:
        desc = m.notes('webapp/src/lib/data.ts').get('functions', {}) or {}
        L += ['## data.ts functions → SQL objects', '',
              '| Function | Does | Objects / tables | Procedures |', '|---|---|---|---|']
        for fn, d in sorted(m.data_fns.items()):
            L.append(f"| `{fn}` | {str(desc.get(fn, '')).replace('|', '/')} | "
                     f"{', '.join('`' + o + '`' for o in d.get('objects', []))} | "
                     f"{', '.join('`' + o + '`' for o in d.get('procs', []))} |")
    return '\n'.join(L) + '\n'


def build_by_table(m):
    readers, writers, diags = defaultdict(list), defaultdict(list), defaultdict(list)
    script_writers, script_refs = defaultdict(list), defaultdict(list)
    DATA_OPS = {'insert', 'update', 'delete', 'truncate', 'merge', 'copy-into'}
    for p, e in m.files.items():
        is_script = e['kind'] == 'script'
        for t, cols in m.reads(p).items():
            if m.obj_type.get(t) != 'table':
                continue
            if is_script and e['auto'].get('scriptEffect') == 'read-only':
                diags[t].append(p)
            elif is_script:
                script_refs[t].append(p)       # migration / redeploy copies that mention the table
            else:
                readers[t].append((p, cols))
        for t, w in m.writes(p).items():
            if m.obj_type.get(t) != 'table':
                continue
            ops = set(w.get('ops', [])) if isinstance(w, dict) and 'ops' in w else set(w) if isinstance(w, dict) else set()
            if ops and ops <= {'drop'} and p == m.obj_file.get(t):
                continue   # its own DROP-IF-EXISTS
            if is_script:
                if ops & DATA_OPS or not ops:
                    script_writers[t].append((p, w))
                else:
                    script_refs[t].append(p)   # DDL-only (ALTER/DROP) migrations
            else:
                writers[t].append((p, w))
    for fn, d in m.data_fns.items():
        for o in d.get('objects', []):
            if m.obj_type.get(o) == 'table':
                readers[o].append((f'webapp/src/lib/data.ts → {fn}()', []))
    L = [HEADER + '# Catalog — by table', '',
         'Each table: its fields (and where their data comes from, where recorded), every file that WRITES it, '
         'every file that READS it, the diagnostic scripts that look at it, and the app routes that reach it.', '']
    for t in m.tables:
        L.append(f'- [`{t}`](#{anchor(t)})')
    L.append('')
    for t in m.tables:
        p = m.obj_file[t]
        n = m.notes(p)
        origins = n.get('origins', {}) if isinstance(n.get('origins'), dict) else {}
        L += [f'## {t}', '', f'Defined in {link(p)} · {m.reviewed(p)}', '']
        if m.purpose(p):
            L += [m.purpose(p), '']
        cols = (m.files[p]['auto'].get('columns') or {}).get(t, [])
        if cols:
            L += ['| Field | Type | Null | Data comes from |', '|---|---|---|---|']
            for c in cols:
                L.append(f"| `{c['name']}` | {c['type']}{' IDENTITY' if c.get('identity') else ''} | "
                         f"{'yes' if c['nullable'] else 'no'} | {origins.get(c['name'], '')} |")
            L.append('')
        if writers[t]:
            L.append('**Written by:**')
            for wp, w in sorted(writers[t], key=lambda x: x[0]):
                L.append(f'- {link(wp)} — {fmt_writes(w)}')
            L.append('')
        if readers[t]:
            L.append('**Read by:**')
            for rp, c in sorted(readers[t], key=lambda x: x[0]):
                ref = link(rp) if rp in m.files else f'`{rp}`'
                L.append(f'- {ref} — {fmt_cols(c) if c else "*(columns not resolved)*"}')
            L.append('')
        if script_writers[t]:
            L.append('**Changed by scripts (fixes / migrations / seeds):**')
            for wp, w in sorted(script_writers[t], key=lambda x: x[0]):
                L.append(f'- {link(wp)} — {fmt_writes(w)}')
            L.append('')
        if diags[t]:
            L.append('**Diagnostics available:** ' + ', '.join(link(d) for d in sorted(diags[t])))
            L.append('')
        refs = sorted(set(script_refs[t]) - {wp for wp, _ in script_writers[t]})
        if refs:
            L.append('**Also referenced by migration / redeploy scripts:** ' + ', '.join(link(r) for r in refs))
            L.append('')
        routes = sorted(m.obj_routes.get(t, []))
        if routes:
            L.append('**Reached from app routes:** ' + ', '.join(f'`{r}`' for r in routes))
            L.append('')
    return '\n'.join(L) + '\n'


def build_by_error(m):
    rows = []
    for p, e in m.files.items():
        n = m.notes(p)
        noted = {(x.get('code'), x.get('message')): x.get('condition', '') for x in n.get('errors', []) or []}
        for x in e['auto'].get('errors', []):
            code = x.get('code') if x.get('code') is not None else (x.get('kind') or '')
            cond = noted.get((x.get('code'), x.get('message')), '') or next(
                (v for (c, msg), v in noted.items() if c == x.get('code') and c is not None), '')
            rows.append((str(code), x['message'], p, x['line'], cond))
    rows.sort(key=lambda r: (not r[0].isdigit(), int(r[0]) if r[0].isdigit() else 0, r[0], r[1]))
    L = [HEADER + '# Catalog — by error', '',
         'Every error the code is written to raise: SQL `THROW` numbers first (51010+ = user-fixable input, '
         '51001–51009 = impossible-state safety nets), then app messages. Search for the text a user reports.', '',
         '| Code / kind | Message | Raised in | Line | Condition |', '|---|---|---|---|---|']
    for code, msg, p, line, cond in rows:
        msg = msg.replace('|', '\\|')
        L.append(f'| {code} | {msg} | {link(p)} | {line} | {cond} |')
    return '\n'.join(L) + '\n'


def build_by_route(m):
    L = [HEADER + '# Catalog — by app route', '',
         'For each screen: the files that make it up, its gates, the data.ts functions and procedures it calls, '
         'the SQL objects and tables behind them, and the errors it can show.', '']
    for route in sorted(m.routes):
        r = m.routes[route]
        L += [f'## `{route}`', '']
        L.append('**Files:** ' + ', '.join(link(f) for f in sorted(r['files'])))
        gates = sorted(set(g['gate'] for _, g in r['gates']))
        if gates:
            L.append('**Gates (auto):** ' + ', '.join(gates))
        if r['dataFns']:
            L.append('**data.ts:** ' + ', '.join(f'`{x}`' for x in sorted(r['dataFns'])))
        if r['procs']:
            L.append('**Procedures:** ' + ', '.join(f'`{x}`' for x in sorted(r['procs'])))
        objs = sorted(o for o in r['objects'] if m.obj_type.get(o) != 'table')
        if objs:
            L.append('**SQL objects:** ' + ', '.join(f'`{x}`' for x in objs))
        tabs = sorted(t for t, rs in m.obj_routes.items() if route in rs and m.obj_type.get(t) == 'table')
        if tabs:
            L.append('**Tables reached:** ' + ', '.join(f'`{x}`' for x in tabs))
        errs = sorted(set(e['message'] for _, e in r['errors'] if e.get('kind') in ('UserError', 'message')))
        if errs:
            L.append('**App messages:** ' + '; '.join(f'“{x}”' for x in errs))
        L.append('')
    return '\n'.join(L) + '\n'


def build_scripts(m):
    scripts = sorted(p for p, e in m.files.items() if e['kind'] == 'script')
    groups = defaultdict(list)
    for p in scripts:
        n = m.notes(p).get('script', {}) or {}
        groups[n.get('kind') or {'read-only': 'diagnostic (auto)', 'writes-data': 'writes data (auto)',
                                 'ddl': 'DDL / object changes (auto)'}[m.files[p]['auto'].get('scriptEffect', 'read-only')]].append(p)
    L = [HEADER + '# Catalog — SQL scripts library', '',
         'Search here BEFORE writing a new diagnostic or fix. Reuse or extend; template it with variables if a '
         'near-duplicate exists. Kinds: diagnostic (read-only) · template (DECLARE variables) · fix/migration · '
         'seed · dev-helper. “(auto)” = classified from the SQL alone, not yet reviewed.', '']
    for g in sorted(groups):
        L.append(f'- [{g}](#{anchor(g)}) ({len(groups[g])})')
    L.append('')
    for g in sorted(groups):
        L += [f'## {g}', '']
        for p in groups[g]:
            a, n = m.files[p]['auto'], m.notes(p)
            s = n.get('script', {}) or {}
            L.append(f'### {os.path.basename(p)}')
            L.append('')
            L.append(f"{link(p)} · {m.reviewed(p)} · last change: {a.get('lastCommit', '')}")
            L.append('')
            q = s.get('question') or m.purpose(p)
            if q:
                L += [q, '']
            facts = [f"effect: **{a.get('scriptEffect')}**"]
            if s.get('target'):
                facts.append(f"target: {s['target']}")
            if s.get('rerunSafe') is not None:
                facts.append(f"re-run safe: {'yes' if s['rerunSafe'] else 'no'}")
            if s.get('applied'):
                facts.append(f"applied: {s['applied']}")
            L.append(' · '.join(facts))
            if a.get('declares'):
                L.append('**Variables:** ' + ', '.join(
                    f"`@{d['name']}`" + (f" = `{d['default']}`" if d.get('default') else '') for d in a['declares']))
            r = m.reads(p)
            if r:
                L.append('**Reads:** ' + ', '.join(f'`{t}`' for t in sorted(r)))
            w = m.writes(p)
            if w:
                L.append('**Writes:** ' + '; '.join(f'`{t}` ({fmt_writes(v)})' for t, v in sorted(w.items())))
            L.append('')
    return '\n'.join(L) + '\n'


def build(cat, out_dir):
    m = Model(cat)
    docs = {'by-file.md': build_by_file(m), 'by-table.md': build_by_table(m), 'by-error.md': build_by_error(m),
            'by-route.md': build_by_route(m), 'scripts.md': build_scripts(m)}
    for name, text in docs.items():
        with open(os.path.join(out_dir, name), 'w', encoding='utf-8', newline='\n') as f:
            f.write(text)
        print(f'build: {name} ({len(text) // 1024} KB)')
