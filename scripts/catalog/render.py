"""
Render docs/catalog/*.md from catalog.json. Called by `catalog.py build`. GENERATED OUTPUT —
never hand-edit the .md files; edit an entry's "notes" in catalog.json and rebuild.
"""
import os
from collections import defaultdict

HEADER = ('<!-- GENERATED by scripts/catalog/catalog.py build — do not edit. Edit notes in '
          'docs/catalog/catalog.json, then rebuild. -->\n\n')


def link(path, root_rel='../../'):
    return f'[{path}]({root_rel}{path})'


def anchor(name):
    return name.lower().replace('.', '').replace('/', '').replace(' ', '-')


class Model:
    """Derived cross-references built once from the catalog."""

    def __init__(self, cat):
        self.files = cat['files']
        self.cat = cat
        # object name -> defining file (canonical dirs win over scripts)
        self.obj_file, self.obj_type = {}, {}
        rank = lambda p: 1 if p.startswith('sql/scripts/') else 0
        for p in sorted(self.files, key=rank):
            for d in self.files[p]['auto'].get('defines', []):
                self.obj_file.setdefault(d['name'], p)
                self.obj_type.setdefault(d['name'], d['type'])
        self.tables = sorted(n for n, t in self.obj_type.items() if t == 'table')
        data = self.files.get('webapp/src/lib/data.ts', {}).get('auto', {}).get('functions', {})
        known = set(self.obj_type)
        self.data_fns = {fn: {**d, 'objects': [o for o in d.get('objects', []) if o in known]}
                         for fn, d in data.items()}
        self.routes = self._routes()
        self.obj_routes = self._object_routes()

    # -- helpers --------------------------------------------------------------------------
    def notes(self, p):
        return self.files[p].get('notes', {}) or {}

    def reads(self, p):
        n = self.notes(p).get('reads')
        return n if isinstance(n, dict) and n else self.files[p]['auto'].get('reads', {})

    def writes(self, p):
        n = self.notes(p).get('writes')
        if isinstance(n, dict) and n:
            return n
        a = self.files[p]['auto']
        own = {d['name'] for d in a.get('defines', [])}
        # an object's own DROP-IF-EXISTS (redeploy idiom) is not a write worth listing
        return {t: w for t, w in a.get('writes', {}).items()
                if not (t in own and set(w.get('ops', [])) <= {'drop'})}

    def purpose(self, p):
        n = self.notes(p).get('purpose')
        if n:
            return n
        a = self.files[p]['auto']
        return a.get('headerPurpose') or a.get('headerScript') or ''

    def reviewed(self, p):
        e = self.files[p]
        if not e.get('reviewedBlob'):
            return 'skeleton (not yet reviewed)'
        if e['reviewedBlob'] != e.get('blob'):
            return 'CHANGED since review'
        return f"reviewed {e.get('reviewedOn', '')}"

    # -- app routes ----------------------------------------------------------------------
    def _routes(self):
        """route -> {files, dataFns, procs, objects, gates}; BFS over local imports from each
        page / route.ts / actions.ts (layout = every page)."""
        out = {}
        entry_files = [p for p, e in self.files.items()
                       if e['kind'] in ('page', 'api-route', 'action') or p.endswith('/layout.tsx')]
        for p in entry_files:
            a = self.files[p]['auto']
            route = '(every page — layout)' if p.endswith('/layout.tsx') else (a.get('route') or '?')
            if self.files[p]['kind'] == 'api-route':
                route = route + ' [API]'
            r = out.setdefault(route, {'files': set(), 'dataFns': set(), 'procs': set(),
                                       'objects': set(), 'gates': [], 'errors': []})
            seen, stack = set(), [p]
            while stack:
                f = stack.pop()
                if f in seen or f not in self.files or f == 'webapp/src/lib/data.ts':
                    continue
                seen.add(f)
                fa = self.files[f]['auto']
                r['files'].add(f)
                r['dataFns'] |= set(fa.get('dataFunctions', []))
                r['procs'] |= set(fa.get('execProcs', []))
                r['objects'] |= set(fa.get('sqlObjects', []))
                for g in fa.get('gates', []):
                    r['gates'].append((f, g))
                for e in fa.get('errors', []):
                    r['errors'].append((f, e))
                stack.extend(fa.get('imports', []))
            for fn in r['dataFns']:
                d = self.data_fns.get(fn, {})
                r['objects'] |= set(d.get('objects', []))
                r['procs'] |= set(d.get('procs', []))
        return out

    def _deps(self, obj):
        """SQL objects/tables an object's defining file reaches (functions, procs, views, tables)."""
        p = self.obj_file.get(obj)
        if not p:
            return set()
        a = self.files[p]['auto']
        return set(a.get('callsFunctions', [])) | set(a.get('execs', [])) | set(self.reads(p)) | set(self.writes(p))

    def _object_routes(self):
        """object/table -> set(routes), following SQL dependencies transitively."""
        res = defaultdict(set)
        for route, r in self.routes.items():
            stack = list(r['objects'] | r['procs'])
            seen = set()
            while stack:
                o = stack.pop()
                if o in seen:
                    continue
                seen.add(o)
                res[o].add(route)
                stack.extend(self._deps(o) - seen)
        return res

    def used_in(self, p):
        """Routes that reach any object this file defines (or the file itself for app code)."""
        routes = set()
        for d in self.files[p]['auto'].get('defines', []):
            routes |= self.obj_routes.get(d['name'], set())
        for route, r in self.routes.items():
            if p in r['files']:
                routes.add(route)
        return sorted(routes)


