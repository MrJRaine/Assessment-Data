 ******************************************************************************/

DROP PROCEDURE IF EXISTS usp_ClearMaintenanceWindow;
GO

CREATE PROCEDURE usp_ClearMaintenanceWindow
    @CallerUPN VARCHAR(255) = NULL
AS
BEGIN
    SET NOCOUNT ON;
    DECLARE @Caller VARCHAR(255) = LOWER(COALESCE(@CallerUPN, CURRENT_USER));

